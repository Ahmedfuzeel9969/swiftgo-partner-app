/** @type {{ lang: 'en' | 'ur', listeners: Set<(lang: string) => void> }} */
const state = {
  lang: loadInitialLang(),
  listeners: new Set(),
};

function loadInitialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "ur") return saved;
  } catch {
    /* ignore */
  }
  return "en";
}

export function getLang() {
  return state.lang;
}

export function t(key) {
  const dict = dictionaries[state.lang] || dictionaries.en;
  return dict[key] ?? dictionaries.en[key] ?? key;
}

/** Locale-aware money for UI (EN: Rs. 142 · UR: ١٤٢ روپے style via locale). */
export function formatMoney(amount) {
  const n = Number(amount) || 0;
  const formatted = n.toLocaleString(state.lang === "ur" ? "ur-PK" : "en-PK");
  return t("currencyAmount").replace("{n}", formatted);
}

export function paymentMethodLabel(methodId) {
  switch (methodId) {
    case "easypaisa":
      return t("payEasypaisa");
    case "jazzcash":
      return t("payJazzCash");
    case "business":
      return t("payBusiness");
    case "cash":
    default:
      return t("payCash");
  }
}

export function subscribe(fn) {
  state.listeners.add(fn);
  return () => state.listeners.delete(fn);
}

export function setLang(lang) {
  if (lang !== "en" && lang !== "ur") return;
  if (state.lang === lang) {
    applyDocumentDirection(lang);
    applyTranslations();
    return;
  }
  state.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
  applyDocumentDirection(lang);
  applyTranslations();
  state.listeners.forEach((fn) => fn(lang));
}

export function applyDocumentDirection(lang = state.lang) {
  const root = document.documentElement;
  const isUrdu = lang === "ur";
  root.lang = isUrdu ? "ur" : "en";
  root.dir = isUrdu ? "rtl" : "ltr";
  root.dataset.lang = lang;
}

export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    el.textContent = t(key);
  });

  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (!key) return;
    el.setAttribute("aria-label", t(key));
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (!key) return;
    el.setAttribute("placeholder", t(key));
  });

  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (!key) return;
    el.setAttribute("title", t(key));
  });

  const docTitle = t("appTitle");
  if (docTitle && root === document) {
    document.title = docTitle;
  }
}

export function initI18n() {
  applyDocumentDirection(state.lang);
  applyTranslations();
  syncLangButtons();
}

export function syncLangButtons(root = document) {
  root.querySelectorAll("[data-lang]").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === state.lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });
}
