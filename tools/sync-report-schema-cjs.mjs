/** Deterministic ESM -> CJS mirror; no hand-maintained report schema fork. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export function generateReportSchemaCjs(source) {
  const names = [...source.matchAll(/^(?:export )?(?:async )?function (\w+)|^export const (\w+)/gm)].map((m) => m[1] || m[2]);
  return '"use strict";\n/** Generated by tools/sync-report-schema-cjs.mjs. */\n' + source
    .replace('import { buildLocationReportingConfigSnapshot } from "./location-reporting-config.mjs";',
      'const { buildLocationReportingConfigSnapshot } = require("./location-reporting-config.js");')
    .replace(/^export /gm, "") + '\nmodule.exports = {\n  ' + names.join(',\n  ') + '\n};\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = generateReportSchemaCjs(fs.readFileSync(path.join(root, "shared/js/ride-location-report-schema.mjs"), "utf8"));
  fs.writeFileSync(path.join(root, "functions/ride-location-report-schema.js"), out);
  console.log("Report schema mirror generated");
}
